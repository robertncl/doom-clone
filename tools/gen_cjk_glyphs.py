#!/usr/bin/env python3
"""Generate src/cjk_glyphs.rs: 16x16 bitmaps for the CJK characters the game
draws, taken from GNU Unifont.

Only characters that appear in src/i18n.rs are embedded (a few dozen), in two
forms: Japanese shapes from unifont_jp (whose kanji come from the public
domain Izumi font) and Chinese shapes from the standard Unifont build.

Usage (download and verify the two files from https://ftp.gnu.org/gnu/unifont/
first; this script only reads them):

    python3 tools/gen_cjk_glyphs.py unifont_all-17.0.05.hex.gz unifont_jp-17.0.05.bdf.gz

Unifont's glyphs are dual-licensed under SIL OFL 1.1 and GNU GPLv2+ with the
font embedding exception; the game uses them under OFL 1.1. See
assets/fonts/UNIFONT-OFL.txt.
"""

import gzip
import pathlib
import re
import sys

VERSION = "17.0.05"
ROOT = pathlib.Path(__file__).resolve().parent.parent


def wanted_chars():
    text = (ROOT / "src" / "i18n.rs").read_text(encoding="utf-8")
    # CJK punctuation, kana, ideographs and fullwidth forms all sit above here.
    return sorted({c for c in text if ord(c) >= 0x2E80})


def rows_from_hex(bits_hex):
    if len(bits_hex) != 64:
        raise ValueError(f"expected a 16x16 glyph, got {len(bits_hex)} hex digits")
    return [int(bits_hex[i:i + 4], 16) for i in range(0, 64, 4)]


def load_hex(path, want):
    out = {}
    with gzip.open(path, "rt", encoding="ascii") as f:
        for line in f:
            cp, _, bits = line.strip().partition(":")
            if cp and chr(int(cp, 16)) in want:
                out[chr(int(cp, 16))] = rows_from_hex(bits)
    return out


def load_bdf(path, want):
    out = {}
    with gzip.open(path, "rt", encoding="utf-8", errors="replace") as f:
        enc, bbx, rows = None, None, None
        for line in f:
            line = line.strip()
            if line.startswith("ENCODING "):
                enc = int(line.split()[1])
            elif line.startswith("BBX "):
                bbx = tuple(int(x) for x in line.split()[1:])
            elif line == "BITMAP":
                rows = []
            elif line == "ENDCHAR":
                if enc is not None and enc >= 0 and chr(enc) in want:
                    w, h = bbx[0], bbx[1]
                    if (w, h) != (16, 16) or len(rows) != 16:
                        raise ValueError(f"U+{enc:04X}: expected 16x16, got {w}x{h}")
                    out[chr(enc)] = rows
                enc, bbx, rows = None, None, None
            elif rows is not None and re.fullmatch(r"[0-9A-Fa-f]{4}", line):
                rows.append(int(line, 16))
    return out


def emit(name, glyphs, chars):
    lines = [f"pub static {name}: [(char, [u16; 16]); {len(chars)}] = ["]
    for c in chars:
        rows = ", ".join(f"0x{r:04X}" for r in glyphs[c])
        lines.append(f"    ('{c}', [{rows}]),")
    lines.append("];")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    want = wanted_chars()
    zh = load_hex(sys.argv[1], set(want))
    ja = load_bdf(sys.argv[2], set(want))
    missing = [c for c in want if c not in zh or c not in ja]
    if missing:
        sys.exit(f"no Unifont glyph for: {' '.join(missing)}")
    src = f"""//! 16x16 bitmaps for the CJK characters in `i18n.rs`, one `u16` per row
//! (most significant bit = leftmost pixel), sorted by character.
//!
//! GENERATED by `tools/gen_cjk_glyphs.py` from GNU Unifont {VERSION}. Do not
//! edit by hand: add the text to `i18n.rs` and rerun the script.
//!
//! Copyright (C) 1998-2026 Roman Czyborra, Paul Hardy, Qianqian Fang, Andrew
//! Miller, Johnnie Weaver, David Corbett, Ælla Chiana Moskopp, Rebecca
//! Bettencourt, Minseo Lee, Ho-Seok Ee, et al. (as stated in the font's
//! COPYRIGHT property); Japanese kanji from the public-domain Izumi font.
//! Used under the SIL Open Font License 1.1 — see
//! `assets/fonts/UNIFONT-OFL.txt`.

/// Japanese forms (from `unifont_jp`).
{emit("JA", ja, want)}

/// Chinese forms (from the standard Unifont build).
{emit("ZH", zh, want)}
"""
    (ROOT / "src" / "cjk_glyphs.rs").write_text(src, encoding="utf-8")
    print(f"wrote {len(want)} glyphs x 2 forms to src/cjk_glyphs.rs")


if __name__ == "__main__":
    main()
